-----------------------------------------------------------
--STG_SALESORDER
-----------------------------------------------------------

CREATE OR REPLACE PROCEDURE SP_LOAD_STG_SALESORDER()
RETURNS STRING
LANGUAGE SQL
AS
BEGIN
    TRUNCATE TABLE STAGING.STG_SALESORDER;
    INSERT INTO STAGING.STG_SALESORDER (	SALESORDERID,	SALESORDERDETAILID,
	ORDERDATE,	DUEDATE,	SHIPDATE,	STATUSID,	CUSTOMERID,	PRODUCTID,
	TAXAMT,	FREIGHT,	ORDERQTY,	UNITPRICE,	UNITPRICEDISCOUNT,	LINETOTAL,
	CREATION_DATE
)

        SELECT H.SALESORDERID, D.SALESORDERDETAILID,H.ORDERDATE, H.DUEDATE, H.SHIPDATE,  H.STATUS, H.CUSTOMERID, D.PRODUCTID, TAXAMT/COUNT(H.SALESORDERID) OVER(PARTITION BY H.SALESORDERID) AS PRO_TAXAMT, FREIGHT/COUNT(H.SALESORDERID) OVER(PARTITION BY H.SALESORDERID) AS PRO_FREIGHT, D.ORDERQTY, D.UNITPRICE, D.UNITPRICEDISCOUNT, D.LINETOTAL, TO_CHAR(CURRENT_TIMESTAMP(),'YYYY-MM-DD HH:MM:SS') AS CREATION_DATE
        
        FROM STAGING.STG_SALESORDERHEADER H 
        JOIN STAGING.STG_SALESORDERDETAIL D ON H.SALESORDERID = D.SALESORDERID ;

        COMMIT;

RETURN 'OK - STG_SALESORDER CARGADO';
END;

