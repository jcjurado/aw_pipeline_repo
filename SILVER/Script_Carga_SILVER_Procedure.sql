--STG_PRODUCT
-----------------------------------------------------------

CREATE OR REPLACE PROCEDURE SP_LOAD_STG_PRODUCT()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
MERGE INTO STAGING.STG_PRODUCT DM
USING (
    SELECT TRY_CAST(P.PRODUCTID AS INTEGER) AS PRODUCTID, P.NAME, P.PRODUCTNUMBER, P.COLOR,
           TRY_CAST(P.LISTPRICE AS FLOAT) AS LISTPRICE, TRY_CAST(P.STANDARDCOST AS FLOAT) AS STANDARCOST,
           SUB.NAME AS SUBCATEGORYNAME, CAT.NAME AS CATEGORYNAME
    FROM RAW.PRODUCT P
    LEFT JOIN RAW.PRODUCTSUBCATEGORY SUB ON P.PRODUCTSUBCATEGORYID = SUB.PRODUCTSUBCATEGORYID
    LEFT JOIN RAW.PRODUCTCATEGORY CAT ON SUB.PRODUCTCATEGORYID = CAT.PRODUCTCATEGORYID
) AUX
ON DM.PRODUCTID = AUX.PRODUCTID
WHEN MATCHED AND (
        DM.NAME               != AUX.NAME
        OR DM.COLOR         != AUX.COLOR
        OR DM.PRODUCT_NUMBER     != AUX.PRODUCTNUMBER
     OR DM.LISTPRICE           != AUX.LISTPRICE
     OR DM.STANDARCOST         != AUX.STANDARCOST
     OR DM.SUBCATEGORYNAME     != AUX.SUBCATEGORYNAME
     OR DM.CATEGORYNAME        != AUX.CATEGORYNAME
) THEN UPDATE SET
    DM.NAME = AUX.NAME, DM.LISTPRICE = AUX.LISTPRICE, DM.STANDARCOST = AUX.STANDARCOST,
    DM.SUBCATEGORYNAME = AUX.SUBCATEGORYNAME, DM.CATEGORYNAME = AUX.CATEGORYNAME
WHEN NOT MATCHED THEN INSERT (PRODUCTID, NAME, PRODUCT_NUMBER, COLOR, LISTPRICE, STANDARCOST, SUBCATEGORYNAME, CATEGORYNAME)
     VALUES (AUX.PRODUCTID, AUX.NAME, AUX.PRODUCTNUMBER, AUX.COLOR, AUX.LISTPRICE, AUX.STANDARCOST, AUX.SUBCATEGORYNAME, AUX.CATEGORYNAME);


    COMMIT;

END;
$$
;
