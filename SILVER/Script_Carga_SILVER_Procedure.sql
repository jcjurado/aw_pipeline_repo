    TRY_CAST(DueDate AS DATE),
    TRY_CAST(ShipDate AS DATE),
    Status,
    TRY_CAST(OnlineOrderFlag AS INTEGER),
    SalesOrderNumber,
    PurchaseOrderNumber,
    AccountNumber,
    TRY_CAST(CustomerID AS INTEGER),
    TRY_CAST(SalesPersonID AS INTEGER),
    TRY_CAST(TerritoryID AS INTEGER),
    TRY_CAST(BillToAddressID AS INTEGER),
    TRY_CAST(ShipToAddressID AS INTEGER),
    TRY_CAST(ShipMethodID AS INTEGER),
    TRY_CAST(CreditCardID AS INTEGER),
    CreditCardApprovalCode,
