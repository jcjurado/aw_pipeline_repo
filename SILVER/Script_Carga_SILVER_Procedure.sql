CREATE OR REPLACE PROCEDURE STAGING.SP_LOAD_STG_SALESORDERHEADER()
RETURNS STRING
LANGUAGE SQL
AS
BEGIN
TRUNCATE TABLE STAGING.STG_SALESORDERHEADER;
    INSERT INTO STAGING.STG_SALESORDERHEADER (SalesOrderID,
    RevisionNumber, OrderDate, DueDate, ShipDate, Status,
    OnlineOrderFlag, SalesOrderNumber, PurchaseOrderNumber, AccountNumber,
